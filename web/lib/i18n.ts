export function formatters(lang: Lang, currency = 'EUR') {
  const locale = LOCALE[lang];
  return {
    /** Montant arrondi à l'unité : indicateurs et tableaux de bord. */
    money: (minor: number) =>
      new Intl.NumberFormat(locale, { style: 'currency', currency, maximumFractionDigits: 0 }).format(minor / 100),
    /** Montant exact au centime : comptes, encaissements et factures. */
    amount: (minor: number) =>
      new Intl.NumberFormat(locale, { style: 'currency', currency, minimumFractionDigits: 2, maximumFractionDigits: 2 }).format(minor / 100),
    percent: (value: number) =>
      new Intl.NumberFormat(locale, { style: 'percent', maximumFractionDigits: 1 }).format(value / 100),
    number: (value: number, digits = 1) => new Intl.NumberFormat(locale, { maximumFractionDigits: digits }).format(value),
    longDate: (iso: string) =>
      new Intl.DateTimeFormat(locale, { weekday: 'long', day: 'numeric', month: 'long', timeZone: 'UTC' }).format(new Date(`${iso}T00:00:00Z`)),
    weekdayShort: (iso: string) => new Intl.DateTimeFormat(locale, { weekday: 'short', timeZone: 'UTC' }).format(new Date(`${iso}T00:00:00Z`)),
    dayOfMonth: (iso: string) => new Intl.DateTimeFormat(locale, { day: 'numeric', timeZone: 'UTC' }).format(new Date(`${iso}T00:00:00Z`)),
    shortDate: (iso: string) =>
      new Intl.DateTimeFormat(locale, { weekday: 'short', day: 'numeric', month: 'short', timeZone: 'UTC' }).format(new Date(`${iso}T00:00:00Z`)),
    time: (d: Date) => new Intl.DateTimeFormat(locale, { hour: '2-digit', minute: '2-digit' }).format(d),
    /** Instant (horodatage) affiché dans le fuseau de l'établissement. */
    instant: (iso: string, timeZone?: string) =>
      new Intl.DateTimeFormat(locale, { weekday: 'short', day: 'numeric', month: 'short', hour: '2-digit', minute: '2-digit', timeZone }).format(new Date(iso)),
    instantDate: (iso: string, timeZone?: string) =>
      new Intl.DateTimeFormat(locale, { weekday: 'short', day: 'numeric', month: 'short', timeZone }).format(new Date(iso)),
  };
}
