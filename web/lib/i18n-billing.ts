/** Taux en points de base → « 10 % » selon la langue. */
export const ratePct = (bp: number, lang: Lang) =>
  new Intl.NumberFormat(lang === 'ar' ? 'ar-u-nu-latn' : lang === 'en' ? 'en-GB' : 'fr-FR', { style: 'percent', maximumFractionDigits: 2 }).format(bp / 10000);
